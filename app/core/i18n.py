def normalize_locale(locale: str | None) -> str:
    if locale in SUPPORTED_LOCALES:
        return str(locale)
    return DEFAULT_LOCALE


def get_locale_name(locale: str, target_locale: str) -> str:
    locale = normalize_locale(locale)
    target_locale = normalize_locale(target_locale)
    return LOCALE_NAMES.get(target_locale, LOCALE_NAMES[DEFAULT_LOCALE]).get(locale, SUPPORTED_LOCALES[locale])


def get_currency_name(locale: str) -> str:
    return CURRENCY_LABELS.get(normalize_locale(locale), CURRENCY_LABELS[DEFAULT_LOCALE])


def t(locale: str, key: str, **kwargs: Any) -> str:
    locale = normalize_locale(locale)
    value = LEXICON.get(locale, LEXICON[DEFAULT_LOCALE]).get(key)
    if value is None:
        value = LEXICON[DEFAULT_LOCALE].get(key, key)
    return value.format(**kwargs)

